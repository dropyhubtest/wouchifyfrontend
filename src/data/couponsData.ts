export type CouponStatus = 'active' | 'inactive' | 'expired' | 'scheduled'
export type CouponType = 'percent' | 'flat' | 'bogo' | 'freebie' | 'cashback' | 'bank'

export interface CouponItem {
  id: string
  title: string
  description: string
  store: string
  category: string
  code: string
  couponType: CouponType
  discount: string          // "50% off", "₹120 off", "Free Delivery"
  discountValue: number     // numeric for sorting
  minOrder: string          // "Min Order: ₹499"
  maxDiscount: string       // "Max ₹250"
  affiliateLink: string
  status: CouponStatus
  isExclusive: boolean
  isFeatured: boolean
  isVerified: boolean
  telegramAlert: boolean
  startDate: string
  expiryDate: string
  expiryText: string        // "Expires in 30 days"
  usageCount: number
  totalUses: number         // cap (0 = unlimited)
  addedOn: string
  storeLogo?: string
}

